#!/usr/bin/env python3
"""
Fix jatpower_jos_service.V_SALES_REPORT so TSLODETA_ITMQT is an AMOUNT (qty*price)
in all three UNION legs, matching jatpt/jatcv/retail.

The service view is a 3-way UNION ALL. Each leg already computes the amount as
`TOTAL`; the report reads `TSLODETA_ITMQT`, which service aliased to a bare
quantity, so the report printed "Rp 1". Point TSLODETA_ITMQT at each leg's amount.

Select items are located with a parenthesis- and backtick-aware scanner, because a
naive split on commas breaks inside coalesce(a, 0).
"""
import os
import re
import subprocess

REPO = "/home/jos.idprofitsol.com/tribin"
OUTDIR = os.path.join(REPO, "database", "views")
PROD_DIR = "/home/profitsol/.hermes/cache/scratch/prod_views"
SCHEMA = "jatpower_jos_service"


def env(key):
    with open(os.path.join(REPO, ".env")) as fh:
        for line in fh:
            if line.startswith(key + "="):
                return line.split("=", 1)[1].strip().strip('"').strip("'")
    raise SystemExit("missing " + key)


def item_before(text, alias_pos):
    """Start index of the select item whose `AS \\`alias\\`` ends at alias_pos.

    Walks backwards tracking () depth and backtick state, stopping at the comma
    that separates this item from the previous one.
    """
    depth = 0
    in_tick = False
    i = alias_pos - 1
    while i >= 0:
        ch = text[i]
        if ch == "`":
            in_tick = not in_tick
        elif not in_tick:
            if ch == ")":
                depth += 1
            elif ch == "(":
                depth -= 1
            elif ch == "," and depth == 0:
                return i + 1
        i -= 1
    return 0


def expression_for(text, alias, search_from=0):
    """The raw SQL expression that aliases to `alias` (without the AS clause)."""
    m = re.search(rf"\s+AS\s+`{re.escape(alias)}`", text[search_from:])
    if not m:
        return None
    start = search_from + item_before(text, search_from + m.start())
    end = search_from + m.start()
    return text[start:end].strip()


def process(src_path, label, schema=SCHEMA):
    text = open(src_path).read()
    marker = f"VIEW `{schema}`.`V_SALES_REPORT` AS"
    if marker not in text:
        raise SystemExit("marker not found in " + src_path)
    body = text.split(marker, 1)[1].strip().rstrip(";").strip()

    parts = re.split(r"(?i)(union all)", body)
    leg_count = sum(1 for p in parts if p.lower().strip() == "union all") + 1
    if leg_count != 3:
        raise SystemExit(f"expected 3 legs, found {leg_count}")

    new_parts = []
    report = []
    for part in parts:
        if part.lower().strip() == "union all":
            new_parts.append(part)
            continue

        qty_expr = expression_for(part, "TSLODETA_ITMQT")
        amount_expr = expression_for(part, "TOTAL")
        if qty_expr is None or amount_expr is None:
            raise SystemExit(f"{label}: could not locate TSLODETA_ITMQT or TOTAL in a leg")

        m = re.search(r"\s+AS\s+`TSLODETA_ITMQT`", part)
        start = item_before(part, m.start())
        new_part = part[:start] + amount_expr + part[m.start():]
        new_parts.append(new_part)
        report.append((qty_expr, amount_expr))

    new_body = "".join(new_parts)

    # ---- assertions -------------------------------------------------------
    assert new_body.count("AS `TSLODETA_ITMQT`") == 3, "must still have 3 TSLODETA_ITMQT aliases"
    assert new_body.count("AS `QTY`") == 3, "QTY must survive in all 3 legs"
    assert new_body.count("AS `TOTAL`") == 3, "TOTAL must survive in all 3 legs"
    assert len(re.findall(r"AS\s+`[A-Z_0-9]+`", new_body)) == len(
        re.findall(r"AS\s+`[A-Z_0-9]+`", body)
    ), "alias count changed"

    out_path = os.path.join(OUTDIR, f"V_SALES_REPORT_TMP.{schema}{label}.sql")
    with open(out_path, "w") as fh:
        fh.write(
            f"-- V_SALES_REPORT_TMP for {schema}{label}\n"
            "-- Generated by build_service_view.py\n"
            "-- Change vs V_SALES_REPORT: TSLODETA_ITMQT carries qty * price (an amount)\n"
            "-- in all three UNION legs, matching jatpt/jatcv/retail, so the report prints\n"
            "-- rupiah instead of 'Rp 1'. QTY is untouched. No branch column: T_POS and\n"
            "-- T_POS_DET carry none, so this company group has no branch filter.\n"
            f"DROP VIEW IF EXISTS `{schema}`.`V_SALES_REPORT_TMP`;\n"
            f"CREATE ALGORITHM=UNDEFINED SQL SECURITY DEFINER VIEW `{schema}`.`V_SALES_REPORT_TMP` AS\n{new_body};\n"
        )
    print(f"{label or '(staging)'} -> {os.path.basename(out_path)}")
    for i, (q, a) in enumerate(report, 1):
        print(f"    leg {i}: was {q[:78]}")
        print(f"            now {a[:78]}")
    return out_path


S, U = env("DB_PASSWORD"), env("DB_USERNAME")
raw = subprocess.run(
    ["mysql", "-h", "127.0.0.1", "-u", U, "-N", "-B", "-e",
     "SELECT REPLACE(VIEW_DEFINITION,'\\\\n','') FROM information_schema.VIEWS "
     f"WHERE TABLE_SCHEMA='{SCHEMA}' AND TABLE_NAME='V_SALES_REPORT'"],
    capture_output=True, text=True, env=dict(os.environ, MYSQL_PWD=S),
).stdout.strip()

with open(os.path.join(OUTDIR, f"V_SALES_REPORT.{SCHEMA}.sql"), "w") as fh:
    fh.write(
        f"-- Verbatim backup of {SCHEMA}.V_SALES_REPORT (staging)\n"
        f"DROP VIEW IF EXISTS `{SCHEMA}`.`V_SALES_REPORT`;\n"
        f"CREATE ALGORITHM=UNDEFINED SQL SECURITY DEFINER VIEW `{SCHEMA}`.`V_SALES_REPORT` AS\n{raw};\n"
    )
print(f"backup refreshed: V_SALES_REPORT.{SCHEMA}.sql\n")

process(os.path.join(OUTDIR, f"V_SALES_REPORT.{SCHEMA}.sql"), "")
prod = os.path.join(PROD_DIR, f"V_SALES_REPORT.{SCHEMA}.PROD.sql")
if os.path.exists(prod):
    process(prod, ".PROD")
